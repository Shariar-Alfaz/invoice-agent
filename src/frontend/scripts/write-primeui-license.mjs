import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const frontendDir = resolve(scriptDir, '..');
const projectRoot = resolve(frontendDir, '..', '..');
const outputFile = resolve(frontendDir, 'src', 'environments', 'primeui-license.generated.ts');
const rootEnv = readEnvFile(resolve(projectRoot, '.env'));
const frontendEnv = readEnvFile(resolve(frontendDir, '.env'));

function readEnvFile(path) {
  try {
    return readFileSync(path, 'utf8');
  } catch {
    return '';
  }
}

function parseEnvValue(content, key) {
  const line = content
    .split(/\r?\n/)
    .find((entry) => entry.trim().startsWith(`${key}=`));

  if (!line) {
    return '';
  }

  const value = line.slice(line.indexOf('=') + 1).trim();
  return value.replace(/^['"]|['"]$/g, '');
}

const license =
  process.env.PRIMEUI_LICENSE ||
  parseEnvValue(rootEnv, 'PRIMEUI_LICENSE') ||
  parseEnvValue(frontendEnv, 'PRIMEUI_LICENSE') ||
  '';
const apiPort =
  process.env.API_PORT ||
  parseEnvValue(rootEnv, 'API_PORT') ||
  parseEnvValue(frontendEnv, 'API_PORT') ||
  '8010';
const apiBaseUrl =
  process.env.FRONTEND_API_BASE_URL ||
  parseEnvValue(rootEnv, 'FRONTEND_API_BASE_URL') ||
  parseEnvValue(frontendEnv, 'FRONTEND_API_BASE_URL') ||
  `http://127.0.0.1:${apiPort}`;

mkdirSync(dirname(outputFile), { recursive: true });
writeFileSync(
  outputFile,
  [
    '// Generated by scripts/write-primeui-license.mjs. Do not edit.',
    `export const PRIMEUI_LICENSE = ${JSON.stringify(license)};`,
    `export const API_BASE_URL = ${JSON.stringify(apiBaseUrl)};`,
    '',
  ].join('\n'),
);

console.log(license ? 'PrimeUI license configured.' : 'PrimeUI license not configured.');
console.log(`Frontend API base URL: ${apiBaseUrl}`);
